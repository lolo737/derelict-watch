// Writes public/config.js from environment variables. Used locally and as the
// build command on Netlify/Vercel, so keys live in the host's settings and
// never in git.
//   SUPABASE_URL=https://xyz.supabase.co SUPABASE_ANON_KEY=eyJ... npm run config
// With neither variable set it does nothing, and the app runs in demo mode.
import { writeFileSync, rmSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const target = fileURLToPath(new URL('../public/config.js', import.meta.url));
const url = process.env.SUPABASE_URL?.trim();
const key = process.env.SUPABASE_ANON_KEY?.trim();

if (!url && !key) {
  console.log('SUPABASE_URL / SUPABASE_ANON_KEY not set: leaving the app in demo mode.');
  process.exit(0);
}
if (!url || !key) {
  console.error('Set BOTH SUPABASE_URL and SUPABASE_ANON_KEY.');
  process.exit(1);
}
if (!/^https:\/\/[a-z0-9.-]+$/i.test(url.replace(/\/+$/, ''))) {
  console.error(`SUPABASE_URL does not look like https://<project>.supabase.co: ${url}`);
  process.exit(1);
}
if (key.startsWith('sb_secret_') || /service_role/.test(Buffer.from(key.split('.')[1] || '', 'base64').toString())) {
  rmSync(target, { force: true });
  console.error('Refusing: that is a secret/service_role key. Use the anon (or sb_publishable_) key.');
  process.exit(1);
}

writeFileSync(target, `// Generated by scripts/write-config.js. Do not commit.
window.DERELICT_WATCH_CONFIG = ${JSON.stringify({ SUPABASE_URL: url.replace(/\/+$/, ''), SUPABASE_ANON_KEY: key }, null, 2)};
`);
console.log(`Wrote ${target}`);
